def dart_enc(model: Model, dart_type: str, expr: str, rust_type: str | None = None) -> str:
    if is_optional(dart_type):
        inner = dart_type[:-1]
        return f"({expr} == null ? null : {dart_enc(model, inner, f'{expr}!', rust_type)})"
    if is_bytes(dart_type, rust_type):
        return f"wireBytes({expr})"
    if dart_type == "Uint16List":
        return f"wireUnits({expr})"
    if dart_type == "Uint32List":
        return f"wireInts({expr})"
    if dart_type in ("bool", "String", "int"):
        return expr
    if dart_type == "BigInt":
        return f"wireBig({expr})"
    if dart_type == "PlatformInt64":
        return f"wireBig(BigInt.from({expr}))"
    element = list_element(dart_type)
    if element is not None:
        return f"[for (final e in {expr}) {dart_enc(model, element, 'e')}]"
    return f"encode{dart_type}({expr})"


def dart_dec(model: Model, dart_type: str, expr: str, rust_type: str | None = None) -> str:
    if is_optional(dart_type):
        inner = dart_type[:-1]
        return f"wireOptional({expr}, (v) => {dart_dec(model, inner, 'v', rust_type)})"
    if is_bytes(dart_type, rust_type):
        return f"readWireBytes({expr})"
    if dart_type == "Uint16List":
        return f"readWireUnits({expr})"
    if dart_type == "Uint32List":
        return f"readWireUint32s({expr})"
    if dart_type == "bool":
        return f"readWireBool({expr})"
    if dart_type == "String":
        return f"readWireString({expr})"
    if dart_type == "int":
        return f"readWireInt({expr})"
    if dart_type == "BigInt":
        return f"readWireBig({expr})"
    if dart_type == "PlatformInt64":
        return f"readWireBig({expr}).toInt()"
    element = list_element(dart_type)
    if element is not None:
        return f"readWireList({expr}, (v) => {dart_dec(model, element, 'v')})"
    return f"decode{dart_type}({expr})"


def dart_signature(function: DartFunction) -> str:
    if not function.params:
        return "()"
    params = []
    for param in function.params:
        params.append(("required " if param.required else "") + f"{param.type} {param.name}")
    return "({" + ", ".join(params) + "})"


def dart_return(function: DartFunction) -> str:
    return f"Future<{function.returns}>" if function.is_async else function.returns


def adapter_calls() -> list[str]:
    text = DART_ADAPTER.read_text(encoding="utf-8")
    names = set(re.findall(r"\b(?:native|_calls)\s*\.([a-z]\w*)\(", text))
    return sorted(names)


def emit_dart(model: Model, surface: dict, types: list[str]) -> str:
    calls = adapter_calls()
    for name in calls:
        if name not in model.functions:
            raise GenerationError(f"adapter calls unknown bridge function {name}")
    remote_read = {camel(name) for name in surface["read"]}
    remote_custom = {camel(name) for name in surface["custom"]}
    missing = (remote_read | remote_custom) - set(calls)
    if missing:
        raise GenerationError(f"surface names functions the adapter does not call: {sorted(missing)}")
    out = [
        f"// {HEADER}",
        "// ignore_for_file: type=lint, unused_import, unnecessary_non_null_assertion",
        "",
        "import 'dart:typed_data';",
        "",
    ]
    for path in model.dart_files:
        out.append(f"import '../../rust/{path.relative_to(ROOT / 'lib/rust').as_posix()}';")
    out.append("import '../../rust/api.dart' as native;")
    out.append("import 'remote/wire_values.dart';")
    out.append("")
    out.append("/// The bridge functions the repository session adapter calls.")
    out.append("abstract interface class RepositorySessionCalls {")
    for name in calls:
        function = model.functions[name]
        out.append(f"  {dart_return(function)} {name}{dart_signature(function)};")
        out.append("")
    out.append("}")
    out.append("")
    out.append("/// Calls the in-process native library.")
    out.append("final class FfiRepositorySessionCalls implements RepositorySessionCalls {")
    out.append("  const FfiRepositorySessionCalls();")
    out.append("")
    for name in calls:
        function = model.functions[name]
        args = ", ".join(f"{p.name}: {p.name}" for p in function.params)
        out.append("  @override")
        out.append(f"  {dart_return(function)} {name}{dart_signature(function)} =>")
        out.append(f"      native.{name}({args});")
        out.append("")
    out.append("}")
    out.append("")
    out.append("/// Read methods a remote helper executes, by wire method name.")
    out.append("const remoteReadMethods = <String>{")
    for name in sorted(remote_read):
        out.append(f"  '{name}',")
    out.append("};")
    out.append("")
    out.append("/// Encodes the remote read surface. A subclass owns transport, session translation and the")
    out.append("/// session lifecycle methods; every other call fails before any byte is sent.")
    out.append("abstract base class WireRepositorySessionCalls implements RepositorySessionCalls {")
    out.append("  /// Sends one read request and returns its decoded JSON result.")
    out.append("  Future<Object?> invokeRead(String method, Map<String, Object?> arguments);")
    out.append("")
    out.append("  /// The helper's session for an application session identifier.")
    out.append("  BigInt helperSession(BigInt sessionId);")
    out.append("")
    out.append("  /// The typed failure for a call the remote surface does not support.")
    out.append("  Never unsupported(String method);")
    out.append("")
    for name in calls:
        function = model.functions[name]
        if name in remote_custom:
            continue
        out.append("  @override")
        if name not in remote_read:
            out.append(f"  {dart_return(function)} {name}{dart_signature(function)} =>")
            out.append(f"      unsupported('{name}');")
            out.append("")
            continue
        rust_fn = model.rust_functions[snake_method(name, surface)]
        rust_types = {camel(n): t for n, t in rust_fn.params}
        out.append(f"  {dart_return(function)} {name}{dart_signature(function)} async {{")
        out.append(f"    final result = await invokeRead('{name}', {{")
        for param in function.params:
            value = "wireBig(helperSession(sessionId))" if param.name == "sessionId" else dart_enc(
                model,
                param.type if param.required or param.type.endswith("?") else param.type + "?",
                param.name,
                rust_types[param.name],
            )
            out.append(f"      '{param.name}': {value},")
        out.append("    });")
        out.append(f"    return {dart_dec(model, function.returns, 'result')};")
        out.append("  }")
        out.append("")
    out.append("}")
    out.append("")
    for name in types:
        if name in model.enums:
            values = model.enums[name].values
            out.append(f"Object encode{name}({name} value) => value.name;")
            out.append("")
            out.append(f"{name} decode{name}(Object? value) => switch (readWireString(value)) {{")
            for v in values:
                out.append(f"  '{v}' => {name}.{v},")
            out.append(f"  _ => throw const WireFormatException('{name}'),")
            out.append("};")
            out.append("")
            continue
        fields = rust_fields(model, name)
        out.append(f"Map<String, Object?> encode{name}({name} value) => {{")
        for rust_name, rust_type, dart_type in fields:
            out.append(f"  '{camel(rust_name)}': {dart_enc(model, dart_type, f'value.{camel(rust_name)}', rust_type)},")
        out.append("};")
        out.append("")
        out.append(f"{name} decode{name}(Object? value) {{")
        names = ", ".join(f"'{camel(n)}'" for n, _, _ in fields)
        out.append(f"  final object = readWireObject(value, '{name}', const [{names}]);")
        out.append(f"  return {name}(")
        for rust_name, rust_type, dart_type in fields:
            out.append(f"    {camel(rust_name)}: {dart_dec(model, dart_type, f'object[{chr(39)}{camel(rust_name)}{chr(39)}]', rust_type)},")
        out.append("  );")
        out.append("}")
        out.append("")
    return "\n".join(out)


def snake_method(name: str, surface: dict) -> str:
    for method in surface["read"] + surface["custom"]:
        if camel(method) == name:
            return method
    raise GenerationError(name)


