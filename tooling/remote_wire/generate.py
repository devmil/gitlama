def dart_enum_values(path: Path, name: str) -> list[str]:
    """The variant names of enum [name] in [path], in declaration order."""
    text = strip_line_comments(path.read_text(encoding="utf-8"))
    match = re.search(r"^enum " + name + r"\b[^{]*\{(.*?)\}", text, re.S | re.M)
    if match is None:
        raise GenerationError(f"enum {name} not found in {path.relative_to(ROOT)}")
    values = []
    for raw in split_top_level(match.group(1).split(";")[0]):
        raw = re.sub(r"^@\w+(\([^)]*\))?\s*", "", raw)
        values.append(re.sub(r"\(.*", "", raw, flags=re.S).strip())
    return values


def emit_enum_mappers() -> str:
    pairs = json.loads(ENUM_PAIRS.read_text(encoding="utf-8"))["pairs"]
    native_libs: set[str] = set()
    model_libs: set[str] = set()
    body: list[str] = []
    seen: set[tuple[str, str]] = set()
    for pair in pairs:
        native_path, native_name = pair["native"].split(":")
        model_path, model_name = pair["model"].split(":")
        if not native_path.startswith("lib/rust/") or not model_path.startswith("lib/models/"):
            raise GenerationError(f"{native_name} -> {model_name}: native must be in lib/rust, model in lib/models")
        native_libs.add(native_path)
        model_libs.add(model_path)
        native_values = dart_enum_values(ROOT / native_path, native_name)
        model_values = dart_enum_values(ROOT / model_path, model_name)
        rename = pair.get("rename", {})
        unknown = set(rename) - set(native_values)
        if unknown:
            raise GenerationError(f"{native_name}: rename names unknown variants {sorted(unknown)}")
        mapped = {value: rename.get(value, value) for value in native_values}
        missing = sorted(value for value in mapped.values() if value not in model_values)
        if missing:
            raise GenerationError(f"{model_name} lacks {native_name} variants {missing}")
        if pair.get("toModel"):
            key = ("native", native_name)
            if key in seen:
                raise GenerationError(f"{native_name} maps to more than one model enum")
            seen.add(key)
            body.append(f"/// [native.{native_name}] as its model value, matched by name.")
            body.append(f"extension {native_name}ToModel on native.{native_name} {{")
            body.append(f"  model.{model_name} toModel() => switch (this) {{")
            for value in native_values:
                body.append(f"    native.{native_name}.{value} => model.{model_name}.{mapped[value]},")
            body.append("  };")
            body.append("}")
            body.append("")
        if pair.get("toNative"):
            key = ("model", model_name)
            if key in seen:
                raise GenerationError(f"{model_name} maps to more than one native enum")
            seen.add(key)
            reverse = {target: source for source, target in mapped.items()}
            extra = sorted(value for value in model_values if value not in reverse)
            if extra:
                raise GenerationError(f"{model_name} variants {extra} have no {native_name} value")
            body.append(f"/// [model.{model_name}] as its bridge value, matched by name.")
            body.append(f"extension {model_name}ToNative on model.{model_name} {{")
            body.append(f"  native.{native_name} toNative() => switch (this) {{")
            for value in model_values:
                body.append(f"    model.{model_name}.{value} => native.{native_name}.{reverse[value]},")
            body.append("  };")
            body.append("}")
            body.append("")
    imports = [f"import '../../{path[len('lib/'):]}' as model;" for path in sorted(model_libs)]
    imports += [f"import '../../{path[len('lib/'):]}' as native;" for path in sorted(native_libs)]
    return "\n".join([f"// {HEADER}", "", *imports, "", *body])


def format_rust(source: str) -> str:
    return subprocess.run(
        [shutil.which("rustfmt") or "rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=source,
        # Explicit, so the generated text (which contains `…`) does not go through the
        # Windows ANSI code page.
        encoding="utf-8",
        capture_output=True,
        check=True,
    ).stdout


def format_dart(source: str) -> str:
    # dart format needs the package's language version, so format inside the package.
    with tempfile.NamedTemporaryFile(
        "w", suffix=".dart", dir=DART_OUT.parent, delete=False, encoding="utf-8"
    ) as handle:
        handle.write(source)
        temporary = Path(handle.name)
    try:
        subprocess.run(
            [shutil.which("dart") or "dart", "format", "--output=write", str(temporary)],
            capture_output=True,
            check=True,
        )
        return temporary.read_text(encoding="utf-8")
    finally:
        os.unlink(temporary)


def main() -> int:
    surface = json.loads(SURFACE.read_text(encoding="utf-8"))
    model = Model()
    parse_dart(model)
    parse_rust(model)
    roots: list[str] = []
    for method in surface["read"] + surface["custom"]:
        dart_fn = model.functions.get(camel(method))
        rust_fn = model.rust_functions.get(method)
        if dart_fn is None or rust_fn is None:
            raise GenerationError(f"surface method {method} is not a bridge function")
        roots.append(dart_fn.returns)
        roots.extend(p.type for p in dart_fn.params)
    roots.extend(surface.get("extra_types", []))
    types = collect_types(model, roots)
    rust = format_rust(emit_rust(model, surface, types) + "\n")
    dart = format_dart(emit_dart(model, surface, types) + "\n")
    mappers = format_dart(emit_enum_mappers() + "\n")
    contract = load_contract()
    contract_rust = format_rust(emit_contract_rust(contract) + "\n")
    limits_rust = format_rust(emit_limits_rust(contract) + "\n")
    contract_dart = format_dart(emit_contract_dart(contract) + "\n")
    check = "--check" in sys.argv
    stale = []
    for path, content in (
        (RUST_OUT, rust),
        (DART_OUT, dart),
        (ENUM_OUT, mappers),
        (CONTRACT_RUST, contract_rust),
        (LIMITS_RUST, limits_rust),
        (CONTRACT_DART, contract_dart),
    ):
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("stale generated remote wire code: " + ", ".join(map(str, stale)), file=sys.stderr)
        print("run python3 tooling/remote_wire/generate.py, then format", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
