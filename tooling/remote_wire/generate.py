class GenerationError(Exception):
    pass


# ---------------------------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------------------------


@dataclass
class DartField:
    name: str
    type: str


@dataclass
class DartClass:
    name: str
    fields: list[DartField]
    source: Path


@dataclass
class DartEnum:
    name: str
    values: list[str]
    source: Path


@dataclass
class DartParam:
    name: str
    type: str
    required: bool


@dataclass
class DartFunction:
    name: str
    returns: str
    params: list[DartParam]
    is_async: bool


@dataclass
class RustStruct:
    name: str
    module: str
    fields: list[tuple[str, str]]


@dataclass
class RustEnum:
    name: str
    module: str
    variants: list[str]


@dataclass
class RustFunction:
    name: str
    params: list[tuple[str, str]]
    # The application function the facade delegates to, when it only delegates.
    target: str | None = None


@dataclass
class Model:
    classes: dict[str, DartClass] = field(default_factory=dict)
    enums: dict[str, DartEnum] = field(default_factory=dict)
    functions: dict[str, DartFunction] = field(default_factory=dict)
    rust_structs: dict[str, RustStruct] = field(default_factory=dict)
    rust_enums: dict[str, RustEnum] = field(default_factory=dict)
    rust_functions: dict[str, RustFunction] = field(default_factory=dict)
    dart_files: list[Path] = field(default_factory=list)


def strip_line_comments(text: str) -> str:
    return re.sub(r"//[^\n]*", "", text)


def split_top_level(text: str, separator: str = ",") -> list[str]:
    parts: list[str] = []
    depth = 0
    current = []
    for char in text:
        if char in "<([{":
            depth += 1
        elif char in ">)]}":
            depth -= 1
        if char == separator and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(char)
    parts.append("".join(current))
    return [part.strip() for part in parts if part.strip()]


def camel(snake: str) -> str:
    head, *rest = snake.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def parse_dart(model: Model) -> None:
    for path in sorted((ROOT / "lib/rust").rglob("*.dart")):
        if path.name.startswith("frb_generated"):
            continue
        model.dart_files.append(path)
        text = strip_line_comments(path.read_text(encoding="utf-8"))
        for match in re.finditer(r"^class (\w+) \{\n(.*?)^\}", text, re.S | re.M):
            name, body = match.group(1), match.group(2)
            fields = [
                DartField(m.group(2), m.group(1))
                for m in re.finditer(r"^  final (.+?) (\w+);$", body, re.M)
            ]
            model.classes[name] = DartClass(name, fields, path)
        for match in re.finditer(r"^enum (\w+) \{(.*?)\}", text, re.S | re.M):
            body = match.group(2).split(";")[0]
            values = [value.strip() for value in body.split(",") if value.strip()]
            model.enums[match.group(1)] = DartEnum(match.group(1), values, path)
        if path.name != "api.dart":
            continue
        header = re.compile(r"^(?:Future<([^\n()=]+?)>|([A-Z][\w<>?]*|void|bool|int|String))\s+(\w+)\(", re.M)
        for match in header.finditer(text):
            depth, index = 1, match.end()
            while depth:
                depth += {"(": 1, ")": -1}.get(text[index], 0)
                index += 1
            if not text[index:].lstrip().startswith("=>"):
                continue
            returns = match.group(1) or match.group(2)
            params_text = text[match.end() : index - 1].strip()
            params: list[DartParam] = []
            if params_text:
                if not (params_text.startswith("{") and params_text.endswith("}")):
                    raise GenerationError(f"{match.group(3)}: positional parameters")
                for raw in split_top_level(params_text[1:-1]):
                    required = raw.startswith("required ")
                    raw = raw.removeprefix("required ").strip()
                    type_, name = raw.rsplit(" ", 1)
                    params.append(DartParam(name, type_, required))
            model.functions[match.group(3)] = DartFunction(
                match.group(3), returns, params, match.group(1) is not None
            )


# The Rust sources, each with the path prefix the generated codecs (in the application crate)
# name its items by: the bridge types, then the application crate, then the FRB facade.
RUST_SOURCES = (
    (ROOT / "rust-core/contract/src", "gitlama_contract"),
    (ROOT / "rust-core/application/src", "crate"),
    (ROOT / "rust-core/src", None),
)


def rust_module(path: Path, source: Path, prefix: str) -> str:
    relative = path.relative_to(source).with_suffix("")
    parts = list(relative.parts)
    if parts[-1] in ("mod", "lib"):
        parts = parts[:-1]
    return "::".join([prefix, *parts])


def parse_rust(model: Model) -> None:
    for source, prefix in RUST_SOURCES:
        for path in sorted(source.rglob("*.rs")):
            if path.name == "frb_generated.rs" or "wire" in path.relative_to(source).parts:
                continue
            if prefix is None and path.name != "api.rs":
                continue  # the desktop-only modules carry nothing the wire adapter can name
            parse_rust_file(model, path, rust_module(path, source, prefix) if prefix else "")


def parse_rust_file(model: Model, path: Path, module: str) -> None:
    text = strip_line_comments(path.read_text(encoding="utf-8"))
    for match in re.finditer(r"^pub struct (\w+) \{\n(.*?)^\}", text, re.S | re.M):
        fields = [
            (m.group(1), m.group(2).strip())
            for m in re.finditer(r"^    pub (\w+): (.+?),$", match.group(2), re.M)
        ]
        model.rust_structs.setdefault(match.group(1), RustStruct(match.group(1), module, fields))
    for match in re.finditer(r"^pub enum (\w+) \{\n(.*?)^\}", text, re.S | re.M):
        body = re.sub(r"#\[[^\]]*\]", "", match.group(2))
        variants = [
            v.strip().split("=")[0].strip() for v in body.split(",") if v.strip()
        ]
        if any(not re.fullmatch(r"\w+", v) for v in variants):
            continue  # data-carrying enums are not part of the bridge surface
        model.rust_enums.setdefault(match.group(1), RustEnum(match.group(1), module, variants))
    if path.name == "api.rs":
        for match in re.finditer(r"^pub fn (\w+)\((.*?)\)[^{]*\{\n(.*?)^\}", text, re.S | re.M):
            params = []
            for raw in split_top_level(match.group(2)):
                name, type_ = raw.split(":", 1)
                params.append((name.strip(), type_.strip()))
            # The wire adapter calls the application function the facade delegates to,
            # never the facade itself; it lives in the application crate.
            target = re.fullmatch(
                r"\s*gitlama_application::(application::\w+::\w+)\(.*\)\s*", match.group(3), re.S
            )
            model.rust_functions[match.group(1)] = RustFunction(
                match.group(1), params, f"crate::{target.group(1)}" if target else None
            )


