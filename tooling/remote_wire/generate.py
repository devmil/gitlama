#!/usr/bin/env python3
"""Generates the remote-workspace wire codecs and the repository session call seam.

Inputs are the committed flutter_rust_bridge Dart bindings (lib/rust) and the Rust sources they
mirror: the bridge types (rust-core/contract), the application crate the wire adapter lives in
(rust-core/application) and the FRB facade (rust-core/src/api.rs). Outputs:

* rust-core/application/src/wire/generated.rs: strict JSON codecs for every type the remote surface carries
  and a dispatcher for its read methods.
* lib/repositories/impl/repository_session_calls.g.dart: the call interface the native session
  repository uses, its FFI forwarding implementation and the wire implementation base.
* rust-core/application/src/wire/contract.rs and lib/models/remote_contract.g.dart: the remote control-plane
  contract (capabilities, write families, outcomes, error codes, bulk methods and limits) from
  tooling/remote_wire/contract.json, so the helper, the core and the client share one copy.
* lib/repositories/impl/native_enum_mappers.g.dart: exhaustive, name-based conversions between
  the bridge enums and the model enums listed in tooling/remote_wire/enum_mappers.json. A
  variant added on one side fails generation or compilation instead of shifting positions.

The surface lives in tooling/remote_wire/surface.json. Run with --check to fail on stale output.
"""
