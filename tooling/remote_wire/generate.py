#!/usr/bin/env python3
"""Generates the remote-workspace wire codecs and the remote control-plane contract.

Inputs are the Rust sources of the remote surface: the bridge types (rust-core/contract), the
application crate the wire adapter lives in (rust-core/application) and the core facade
(rust-core/src/api.rs), whose functions name the surface methods. Outputs:

* rust-core/application/src/wire/generated.rs: strict JSON codecs for every type the remote
  surface carries and a dispatcher for its read methods.
* rust-core/application/src/wire/contract.rs and rust-core/application/src/domain/limits.rs:
  the remote control-plane contract (capabilities, write families, outcomes, error codes, bulk
  methods and limits) from tooling/remote_wire/contract.json, so the helper, the core and the
  client share one copy.

Wire field names are the camelCase Rust names; enum values are the variant names with a
lowercase first letter. The surface lives in tooling/remote_wire/surface.json. Run with --check
to fail on stale output.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SURFACE = ROOT / "tooling/remote_wire/surface.json"
RUST_OUT = ROOT / "rust-core/application/src/wire/generated.rs"
CONTRACT = ROOT / "tooling/remote_wire/contract.json"
CONTRACT_RUST = ROOT / "rust-core/application/src/wire/contract.rs"
LIMITS_RUST = ROOT / "rust-core/application/src/domain/limits.rs"

HEADER = "GENERATED by tooling/remote_wire/generate.py. Do not edit."


class GenerationError(Exception):
    pass


# ---------------------------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------------------------


@dataclass
class WireField:
    name: str
    type: str


@dataclass
class WireClass:
    name: str
    fields: list[WireField]


@dataclass
class WireEnum:
    name: str
    values: list[str]


@dataclass
class WireParam:
    name: str
    type: str
    required: bool


@dataclass
class WireFunction:
    name: str
    returns: str
    params: list[WireParam]


@dataclass
class RustStruct:
    name: str
    module: str
    fields: list[tuple[str, str]]


@dataclass
class RustEnum:
    name: str
    module: str
    variants: list[str]


@dataclass
class RustFunction:
    name: str
    params: list[tuple[str, str]]
    returns: str
    # The application function the facade delegates to, when it only delegates.
    target: str | None = None


@dataclass
class Model:
    classes: dict[str, WireClass] = field(default_factory=dict)
    enums: dict[str, WireEnum] = field(default_factory=dict)
    functions: dict[str, WireFunction] = field(default_factory=dict)
    rust_structs: dict[str, RustStruct] = field(default_factory=dict)
    rust_enums: dict[str, RustEnum] = field(default_factory=dict)
    rust_functions: dict[str, RustFunction] = field(default_factory=dict)


def strip_line_comments(text: str) -> str:
    return re.sub(r"//[^\n]*", "", text)


def split_top_level(text: str, separator: str = ",") -> list[str]:
    parts: list[str] = []
    depth = 0
    current = []
    for char in text:
        if char in "<([{":
            depth += 1
        elif char in ">)]}":
            depth -= 1
        if char == separator and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(char)
    parts.append("".join(current))
    return [part.strip() for part in parts if part.strip()]


def camel(snake: str) -> str:
    head, *rest = snake.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)



# The Rust sources, each with the path prefix the generated codecs (in the application crate)
# name its items by: the bridge types, then the application crate, then the FRB facade.
RUST_SOURCES = (
    (ROOT / "rust-core/contract/src", "gitlama_contract"),
    (ROOT / "rust-core/application/src", "crate"),
    (ROOT / "rust-core/src", None),
)


def rust_module(path: Path, source: Path, prefix: str) -> str:
    relative = path.relative_to(source).with_suffix("")
    parts = list(relative.parts)
    if parts[-1] in ("mod", "lib"):
        parts = parts[:-1]
    return "::".join([prefix, *parts])


def parse_rust(model: Model) -> None:
    for source, prefix in RUST_SOURCES:
        for path in sorted(source.rglob("*.rs")):
            if path.name == "frb_generated.rs" or "wire" in path.relative_to(source).parts:
                continue
            if prefix is None and path.name != "api.rs":
                continue  # the desktop-only modules carry nothing the wire adapter can name
            parse_rust_file(model, path, rust_module(path, source, prefix) if prefix else "")


def parse_rust_file(model: Model, path: Path, module: str) -> None:
    text = strip_line_comments(path.read_text(encoding="utf-8"))
    for match in re.finditer(r"^pub struct (\w+) \{\n(.*?)^\}", text, re.S | re.M):
        fields = [
            (m.group(1), m.group(2).strip())
            for m in re.finditer(r"^    pub (\w+): (.+?),$", match.group(2), re.M)
        ]
        model.rust_structs.setdefault(match.group(1), RustStruct(match.group(1), module, fields))
    for match in re.finditer(r"^pub enum (\w+) \{\n(.*?)^\}", text, re.S | re.M):
        body = re.sub(r"#\[[^\]]*\]", "", match.group(2))
        variants = [
            v.strip().split("=")[0].strip() for v in body.split(",") if v.strip()
        ]
        if any(not re.fullmatch(r"\w+", v) for v in variants):
            continue  # data-carrying enums are not part of the bridge surface
        model.rust_enums.setdefault(match.group(1), RustEnum(match.group(1), module, variants))
    if path.name == "api.rs":
        for match in re.finditer(r"^pub fn (\w+)\((.*?)\)\s*(?:->\s*([^{]+?))?\s*\{\n(.*?)^\}", text, re.S | re.M):
            params = []
            for raw in split_top_level(match.group(2)):
                name, type_ = raw.split(":", 1)
                params.append((name.strip(), type_.strip()))
            # The wire adapter calls the application function the facade delegates to,
            # never the facade itself; it lives in the application crate.
            target = re.fullmatch(
                r"\s*gitlama_application::(application::\w+::\w+)\(.*\)\s*", match.group(4), re.S
            )
            model.rust_functions[match.group(1)] = RustFunction(
                match.group(1), params, (match.group(3) or "()").strip(), f"crate::{target.group(1)}" if target else None
            )




# The wire shapes: each Rust type in the vocabulary of the codecs (`T?` optional, `List<T>`,
# typed integer lists and the integer widths), with the enum values that are keywords of the
# earlier client language suffixed with `_` so the wire values stay what released helpers send.
KEYWORDS = {
    "abstract", "as", "assert", "async", "await", "break", "case", "catch", "class", "const",
    "continue", "covariant", "default", "deferred", "do", "dynamic", "else", "enum", "export",
    "extends", "extension", "external", "factory", "false", "final", "finally", "for", "get",
    "hide", "if", "implements", "import", "in", "interface", "is", "late", "library", "mixin",
    "new", "null", "on", "operator", "part", "required", "rethrow", "return", "set", "show",
    "static", "super", "switch", "sync", "this", "throw", "true", "try", "typedef", "var",
    "void", "while", "with", "yield",
}


def wire_shape(rust_type: str) -> str:
    rust_type = rust_type.strip()
    generic = re.fullmatch(r"(?:[\w:]+::)?(Option|Vec|Box)<(.+)>", rust_type)
    if generic:
        outer, inner = generic.group(1), generic.group(2).strip()
        if outer == "Option":
            return wire_shape(inner) + "?"
        if outer == "Box":
            return wire_shape(inner)
        typed = {"u8": "Uint8List", "u16": "Uint16List", "u32": "Uint32List"}.get(inner)
        return typed or f"List<{wire_shape(inner)}>"
    if rust_type in ("bool", "String"):
        return rust_type
    if rust_type in ("u8", "u16", "u32", "i8", "i16", "i32"):
        return "int"
    if rust_type == "i64":
        return "PlatformInt64"
    if rust_type in ("u64", "usize", "isize", "i128", "u128"):
        return "BigInt"
    if rust_type == "()":
        return "void"
    return rust_type.rsplit("::", 1)[-1]


def wire_value(variant: str) -> str:
    value = variant[:1].lower() + variant[1:]
    return value + "_" if value in KEYWORDS else value


def build_wire_model(model: Model) -> None:
    for name, struct in model.rust_structs.items():
        model.classes[name] = WireClass(
            name, [WireField(camel(field_name), wire_shape(type_)) for field_name, type_ in struct.fields]
        )
    for name, enum in model.rust_enums.items():
        model.enums[name] = WireEnum(name, [wire_value(variant) for variant in enum.variants])
    for name, function in model.rust_functions.items():
        params = [
            WireParam(camel(param), wire_shape(type_), not wire_shape(type_).endswith("?"))
            for param, type_ in function.params
        ]
        model.functions[camel(name)] = WireFunction(camel(name), wire_shape(function.returns), params)


