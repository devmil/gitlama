def snake_type(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def rust_enc(model: Model, dart_type: str, expr: str, rust_type: str | None = None) -> str:
    """A Rust expression encoding `expr` (a reference) as a JSON value."""
    if is_optional(dart_type):
        inner = dart_type[:-1]
        inner_rust = None
        if rust_type and rust_type.startswith("Option<"):
            inner_rust = rust_type[len("Option<") : -1]
        return f"w::opt_e({expr}, |v| {rust_enc(model, inner, 'v', inner_rust)})"
    if is_bytes(dart_type, rust_type):
        return f"w::bytes_e({expr})"
    if dart_type == "Uint16List":
        return f"w::units_e({expr})"
    if dart_type == "Uint32List":
        return f"w::list_e({expr}, |v| w::int_e(v))"
    if dart_type == "bool":
        return f"w::bool_e({expr})"
    if dart_type == "int":
        return f"w::int_e({expr})"
    if dart_type in ("BigInt", "PlatformInt64"):
        return f"w::big_e({expr})"
    if dart_type == "String":
        return f"w::str_e({expr})"
    element = list_element(dart_type)
    if element is not None:
        inner_rust = None
        if rust_type and rust_type.startswith("Vec<"):
            inner_rust = rust_type[len("Vec<") : -1]
        return f"w::list_e({expr}, |v| {rust_enc(model, element, 'v', inner_rust)})"
    return f"enc_{snake_type(dart_type)}({expr})"


def rust_dec(model: Model, dart_type: str, expr: str, rust_type: str | None = None) -> str:
    """A Rust expression decoding JSON value reference `expr`, yielding Result<T, WireError>."""
    if is_optional(dart_type):
        inner = dart_type[:-1]
        inner_rust = None
        if rust_type and rust_type.startswith("Option<"):
            inner_rust = rust_type[len("Option<") : -1]
        return f"w::opt_d({expr}, |v| {rust_dec(model, inner, 'v', inner_rust)})"
    if is_bytes(dart_type, rust_type):
        return f"w::bytes_d({expr})"
    if dart_type == "Uint16List":
        return f"w::units_d({expr})"
    if dart_type == "Uint32List":
        return f"w::list_d({expr}, |v| w::int_d(v))"
    if dart_type == "bool":
        return f"w::bool_d({expr})"
    if dart_type == "int":
        return f"w::int_d({expr})"
    if dart_type in ("BigInt", "PlatformInt64"):
        return f"w::big_d({expr})"
    if dart_type == "String":
        return f"w::str_d({expr})"
    element = list_element(dart_type)
    if element is not None:
        inner_rust = None
        if rust_type and rust_type.startswith("Vec<"):
            inner_rust = rust_type[len("Vec<") : -1]
        return f"w::list_d({expr}, |v| {rust_dec(model, element, 'v', inner_rust)})"
    return f"dec_{snake_type(dart_type)}({expr})"


def emit_rust(model: Model, surface: dict, types: list[str]) -> str:
    out = [
        f"// {HEADER}",
        "//! Strict JSON codecs for the remote repository surface and its read dispatcher.",
        "#![allow(clippy::too_many_lines, clippy::redundant_closure)]",
        "#![allow(clippy::redundant_closure_for_method_calls)]",
        "#![allow(clippy::needless_pass_by_value, clippy::trivially_copy_pass_by_ref)]",
        "use super::runtime as w;",
        "use super::runtime::{Value, WireError};",
        "",
    ]
    for name in types:
        snake = snake_type(name)
        if name in model.enums:
            enum = model.rust_enums[name]
            path = f"{enum.module}::{name}"
            variants = rust_variants(model, name)
            out.append(f"pub fn enc_{snake}(value: &{path}) -> Value {{")
            out.append("    Value::String(match value {")
            for variant, wire in variants:
                out.append(f'        {path}::{variant} => "{wire}",')
            out.append("    }.to_owned())")
            out.append("}")
            out.append("")
            out.append(f"pub fn dec_{snake}(value: &Value) -> Result<{path}, WireError> {{")
            out.append("    match w::str_ref(value)? {")
            for variant, wire in variants:
                out.append(f'        "{wire}" => Ok({path}::{variant}),')
            out.append(f'        _ => Err(WireError::invalid("{name}")),')
            out.append("    }")
            out.append("}")
            out.append("")
            continue
        struct = model.rust_structs[name]
        path = f"{struct.module}::{name}"
        fields = rust_fields(model, name)
        out.append(f"pub fn enc_{snake}(value: &{path}) -> Value {{")
        out.append("    let mut map = w::Map::new();")
        for rust_name, rust_type, dart_type in fields:
            out.append(
                f'    map.insert("{camel(rust_name)}".to_owned(), '
                f"{rust_enc(model, dart_type, f'&value.{rust_name}', rust_type)});"
            )
        out.append("    Value::Object(map)")
        out.append("}")
        out.append("")
        out.append(f"pub fn dec_{snake}(value: &Value) -> Result<{path}, WireError> {{")
        names = ", ".join(f'"{camel(n)}"' for n, _, _ in fields)
        out.append(f'    let object = w::object(value, "{name}", &[{names}])?;')
        out.append(f"    Ok({path} {{")
        for rust_name, rust_type, dart_type in fields:
            decoder = rust_dec(model, dart_type, f'object.field("{camel(rust_name)}")', rust_type)
            out.append(f"        {rust_name}: {decoder}?,")
        out.append("    })")
        out.append("}")
        out.append("")

    # Argument decoding plus dispatch for read methods.
    out.append("/// The read methods a helper may execute. Mutations are never dispatched here.")
    out.append("pub const READ_METHODS: &[&str] = &[")
    for method in surface["read"]:
        out.append(f'    "{camel(method)}",')
    out.append("];")
    out.append("")
    out.append("/// Runs one allowlisted read method. `None` means the method is not a read method.")
    out.append("pub fn dispatch_read(method: &str, args: &Value) -> Option<Result<Value, WireError>> {")
    out.append("    let result = match method {")
    for method in surface["read"]:
        rust_fn = model.rust_functions[method]
        dart_fn = model.functions[camel(method)]
        dart_params = {p.name: p for p in dart_fn.params}
        names = ", ".join(f'"{camel(n)}"' for n, _ in rust_fn.params)
        out.append(f'        "{camel(method)}" => (|| {{')
        out.append(f'            let args = w::object(args, "{camel(method)}", &[{names}])?;')
        call_args = []
        for rust_name, rust_type in rust_fn.params:
            param = dart_params[camel(rust_name)]
            dart_type = param.type if param.required or param.type.endswith("?") else param.type + "?"
            call_args.append(rust_dec(model, dart_type, f'args.field("{camel(rust_name)}")', rust_type) + "?")
        result_type = dart_fn.returns
        if rust_fn.target is None:
            raise GenerationError(f"read method {method} is not a delegation to gitlama_application::application")
        out.append(f"            let result = {rust_fn.target}({', '.join(call_args)});")
        out.append(f"            Ok({rust_enc(model, result_type, '&result')})")
        out.append("        })(),")
    out.append("        _ => return None,")
    out.append("    };")
    out.append("    Some(result)")
    out.append("}")
    out.append("")
    return "\n".join(out)


