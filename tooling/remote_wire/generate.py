SCALARS = {"bool", "int", "BigInt", "PlatformInt64", "String", "Uint8List", "Uint16List", "Uint32List"}


def is_optional(dart_type: str) -> bool:
    return dart_type.endswith("?")


def list_element(dart_type: str) -> str | None:
    match = re.fullmatch(r"List<(.+)>", dart_type)
    return match.group(1) if match else None


def collect_types(model: Model, roots: list[str]) -> list[str]:
    seen: list[str] = []

    def visit(dart_type: str) -> None:
        dart_type = dart_type.removesuffix("?")
        element = list_element(dart_type)
        if element is not None:
            visit(element)
            return
        if dart_type in SCALARS:
            return
        if dart_type in seen:
            return
        if dart_type in model.enums:
            seen.append(dart_type)
            return
        if dart_type not in model.classes:
            raise GenerationError(f"unknown Dart type {dart_type}")
        seen.append(dart_type)
        for field_ in model.classes[dart_type].fields:
            visit(field_.type)

    for root in roots:
        visit(root)
    return seen


def rust_fields(model: Model, name: str) -> list[tuple[str, str, str]]:
    """(rust name, rust type, dart type) for a mirrored struct, checked against the Dart class."""
    struct = model.rust_structs.get(name)
    if struct is None:
        raise GenerationError(f"missing Rust struct {name}")
    dart = {f.name: f.type for f in model.classes[name].fields}
    pairs = []
    for rust_name, rust_type in struct.fields:
        dart_name = camel(rust_name)
        if dart_name not in dart:
            raise GenerationError(f"{name}.{rust_name} has no Dart field {dart_name}")
        pairs.append((rust_name, rust_type, dart.pop(dart_name)))
    if dart:
        raise GenerationError(f"{name}: Dart fields without Rust source: {sorted(dart)}")
    return pairs


def rust_variants(model: Model, name: str) -> list[tuple[str, str]]:
    enum = model.rust_enums.get(name)
    if enum is None:
        raise GenerationError(f"missing Rust enum {name}")
    dart = model.enums[name].values
    pairs = []
    for variant in enum.variants:
        wire = variant[:1].lower() + variant[1:]
        # The bridge appends `_` to values that are Dart keywords.
        if wire not in dart and wire + "_" in dart:
            wire += "_"
        if wire not in dart:
            raise GenerationError(f"{name}::{variant} has no Dart value {wire}")
        pairs.append((variant, wire))
    if len(pairs) != len(dart):
        raise GenerationError(f"{name}: Dart and Rust values differ")
    return pairs


def is_bytes(dart_type: str, rust_type: str | None) -> bool:
    base = dart_type.removesuffix("?")
    if base == "Uint8List":
        return True
    if base == "List<int>":
        if rust_type is None or "Vec<u8>" not in rust_type:
            raise GenerationError(f"List<int> without a Vec<u8> source ({rust_type})")
        return True
    return False


