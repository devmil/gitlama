    for f in contract["families"]:
        out += dart_doc(f.get("doc"), "  ") + [f"  {f['name']}(RemoteCapability.{f['capability']}, direct: {str(f['direct']).lower()}),"]
    out[-1] = out[-1][:-1] + ";"
    out += ["", "  const RemoteOperationFamily(this.capability, {required this.direct});", "",
            "  /// The capability the family needs.", "  final RemoteCapability capability;", "",
            "  /// Execute repeats the previewed request instead of a core preview token.", "  final bool direct;", "}", ""]
