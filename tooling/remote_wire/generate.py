def pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


def screaming(name: str) -> str:
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).upper()


def load_contract() -> dict:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    capabilities = {c["name"] for c in contract["capabilities"]}
    for family in contract["families"]:
        if family["capability"] not in capabilities:
            raise GenerationError(f"family {family['name']}: unknown capability")
        if pascal(family["name"]) != family["method"]:
            raise GenerationError(f"family {family['name']}: method suffix must be {pascal(family['name'])}")
    for group in ("errors", "fatalErrors", "bulk"):
        if len(set(contract[group])) != len(contract[group]):
            raise GenerationError(f"duplicate entry in {group}")
    return contract


def rust_doc(doc: str | None, indent: str = "") -> list[str]:
    return [f"{indent}/// {doc}"] if doc else []


def rust_enum(name: str, values: list[dict], doc: str) -> list[str]:
    lines = [f"/// {doc}", "#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]", f"pub enum {name} {{"]
    for value in values:
        lines += rust_doc(value.get("doc"), "    ") + [f"    {pascal(value['name'])},"]
    lines += ["}", "", f"impl {name} {{", f"    pub const ALL: [Self; {len(values)}] = ["]
    lines += [f"        Self::{pascal(value['name'])}," for value in values]
    lines += ["    ];", "", "    /// The protocol name.", "    #[must_use]", "    pub const fn name(self) -> &'static str {", "        match self {"]
    lines += [f'            Self::{pascal(value["name"])} => "{value["name"]}",' for value in values]
    lines += ["        }", "    }", "", "    /// The value a protocol name denotes.", "    #[must_use]", "    pub fn parse(name: &str) -> Option<Self> {", "        Self::ALL.into_iter().find(|value| value.name() == name)", "    }"]
    return lines


def emit_limits_rust(contract: dict) -> str:
    out = [f"// {HEADER}", "//! The product limits from tooling/remote_wire/contract.json, shared by the core, the",
           "//! remote helper and the client.", ""]
    for limit in contract["limits"]:
        out += rust_doc(limit["doc"]) + [f"pub const {screaming(limit['name'])}: usize = {limit['value']};"]
    return "\n".join(out)


def emit_contract_rust(contract: dict) -> str:
    out = [f"// {HEADER}", "//! The remote control-plane contract from tooling/remote_wire/contract.json.", "",
           "pub use crate::domain::limits::*;", ""]
    caps = contract["capabilities"]
    out += rust_enum("RemoteCapability", caps, "A capability a helper offers and a client requests.")
    writes = [c for c in caps if c["write"]]
    receipts = [c for c in writes if c.get("receipt")]
    out += ["", "    /// Every write capability; a helper offers them only with a usable receipt store.",
            f"    pub const WRITES: [Self; {len(writes)}] = ["]
    out += [f"        Self::{pascal(c['name'])}," for c in writes]
    out += ["    ];", "", "    /// The write capabilities whose operations carry a durable receipt.",
            f"    pub const RECEIPT_WRITES: [Self; {len(receipts)}] = ["]
    out += [f"        Self::{pascal(c['name'])}," for c in receipts]
    out += ["    ];", "", "    #[must_use]", "    pub const fn is_write(self) -> bool {",
            "        matches!(self, " + " | ".join(f"Self::{pascal(c['name'])}" for c in writes) + ")", "    }", "}", ""]
    fams = contract["families"]
    out += rust_enum("RemoteWriteFamily", fams, "The family of a remote write; its methods are `preview…` and `execute…`.")
    out += ["", "    /// The family of a `preview…` or `execute…` method suffix.", "    #[must_use]",
            "    pub fn of_method(suffix: &str) -> Option<Self> {", "        match suffix {"]
    out += [f'            "{f["method"]}" => Some(Self::{pascal(f["name"])}),' for f in fams]
    out += ["            _ => None,", "        }", "    }", "", "    /// The capability the family needs.", "    #[must_use]",
            "    pub const fn capability(self) -> RemoteCapability {", "        match self {"]
    out += [f"            Self::{pascal(f['name'])} => RemoteCapability::{pascal(f['capability'])}," for f in fams]
    out += ["        }", "    }", "", "    /// Families the core runs without a preview of its own: Execute carries the request",
            "    /// again and must match the digest of the previewed one.", "    #[must_use]",
            "    pub const fn direct(self) -> bool {",
            "        matches!(self, " + " | ".join(f"Self::{pascal(f['name'])}" for f in fams if f["direct"]) + ")", "    }", "}", ""]
    outs = contract["outcomes"]
    out += rust_enum("RemoteOutcome", outs, "What is known about a remote write.")
    out += ["", "    /// Whether the outcome settles the operation.", "    #[must_use]", "    pub const fn definite(self) -> bool {",
            "        matches!(self, " + " | ".join(f"Self::{pascal(o['name'])}" for o in outs if o["definite"]) + ")", "    }", "}", ""]
    errs = [{"name": n} for n in contract["errors"]]
    out += rust_enum("RemoteErrorCode", errs, "An error code a helper returns for one request.") + ["}", ""]
    fatal = [{"name": n} for n in contract["fatalErrors"]]
    out += rust_enum("RemoteFatalCode", fatal, "An error code that ends the connection.") + ["}", ""]
    out += ["/// Reads that may take minutes; a helper serves them after interactive reads.",
            f"pub const BULK_METHODS: [&str; {len(contract['bulk'])}] = ["]
    out += [f'    "{m}",' for m in contract["bulk"]] + ["];"]
    return "\n".join(out)


