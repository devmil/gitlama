SCALARS = {"bool", "int", "BigInt", "PlatformInt64", "String", "Uint8List", "Uint16List", "Uint32List"}


def is_optional(wire_type: str) -> bool:
    return wire_type.endswith("?")


def list_element(wire_type: str) -> str | None:
    match = re.fullmatch(r"List<(.+)>", wire_type)
    return match.group(1) if match else None


def collect_types(model: Model, roots: list[str]) -> list[str]:
    seen: list[str] = []

    def visit(wire_type: str) -> None:
        wire_type = wire_type.removesuffix("?")
        element = list_element(wire_type)
        if element is not None:
            visit(element)
            return
        if wire_type in SCALARS:
            return
        if wire_type in seen:
            return
        if wire_type in model.enums:
            seen.append(wire_type)
            return
        if wire_type not in model.classes:
            raise GenerationError(f"unknown wire type {wire_type}")
        seen.append(wire_type)
        for field_ in model.classes[wire_type].fields:
            visit(field_.type)

    for root in roots:
        visit(root)
    return seen


def rust_fields(model: Model, name: str) -> list[tuple[str, str, str]]:
    """(rust name, rust type, wire type) for a mirrored struct, checked against its wire shape."""
    struct = model.rust_structs.get(name)
    if struct is None:
        raise GenerationError(f"missing Rust struct {name}")
    wire = {f.name: f.type for f in model.classes[name].fields}
    pairs = []
    for rust_name, rust_type in struct.fields:
        wire_name = camel(rust_name)
        if wire_name not in wire:
            raise GenerationError(f"{name}.{rust_name} has no wire field {wire_name}")
        pairs.append((rust_name, rust_type, wire.pop(wire_name)))
    if wire:
        raise GenerationError(f"{name}: wire fields without Rust source: {sorted(wire)}")
    return pairs


def rust_variants(model: Model, name: str) -> list[tuple[str, str]]:
    enum = model.rust_enums.get(name)
    if enum is None:
        raise GenerationError(f"missing Rust enum {name}")
    values = model.enums[name].values
    pairs = []
    for variant in enum.variants:
        wire = variant[:1].lower() + variant[1:]
        # Values that are keywords of the earlier client language keep their `_` suffix.
        if wire not in values and wire + "_" in values:
            wire += "_"
        if wire not in values:
            raise GenerationError(f"{name}::{variant} has no wire value {wire}")
        pairs.append((variant, wire))
    if len(pairs) != len(values):
        raise GenerationError(f"{name}: wire and Rust values differ")
    return pairs


def is_bytes(wire_type: str, rust_type: str | None) -> bool:
    base = wire_type.removesuffix("?")
    if base == "Uint8List":
        return True
    if base == "List<int>":
        if rust_type is None or "Vec<u8>" not in rust_type:
            raise GenerationError(f"List<int> without a Vec<u8> source ({rust_type})")
        return True
    return False


