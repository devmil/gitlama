#!/usr/bin/env python3
"""Generates the repository session call seam of the desktop application.

Inputs:
* rust-core/src/api.rs: the in-process facade's function signatures;
* tooling/remote_wire/session_calls.json: the functions a session backend serves;
* tooling/remote_wire/surface.json: which of them the remote helper executes;
* rust-core/application/src/wire/generated.rs: the helper's read dispatcher, whose argument
  decoders and result encoders the client mirrors, so both sides use one codec.

Output: rust-core/desktop/workbench/src/backend/calls.rs with
* `SessionCalls`, the async call interface every session backend implements;
* `LocalCalls`, which runs the in-process facade on the blocking pool;
* `wire_reads`, one client function per remote read method;
* `RemoteCallsBase`, the remote backend's routing: read methods go to `wire_reads`, custom
  methods to the hand-written `RemoteCustom` implementation, all others fail as unsupported;
* `RoutedCalls`, which hands each call to the backend of its session (or, for an open, of
  its path's authority) through a `CallRouter`; calls without either run locally.

  python3 tooling/remote_wire/generate_calls.py          write the seam
  python3 tooling/remote_wire/generate_calls.py --check  fail when it is stale
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
API = ROOT / "rust-core/src/api.rs"
CALLS = ROOT / "tooling/remote_wire/session_calls.json"
SURFACE = ROOT / "tooling/remote_wire/surface.json"
DISPATCH = ROOT / "rust-core/application/src/wire/generated.rs"
OUTPUT = ROOT / "rust-core/desktop/workbench/src/backend/calls.rs"
HEADER = "// GENERATED by tooling/remote_wire/generate_calls.py. Do not edit."


class GenerationError(Exception):
    pass


@dataclass
class Function:
    name: str
    params: list[tuple[str, str]]
    returns: str


def split_top_level(text: str, separator: str = ",") -> list[str]:
    parts, depth, current = [], 0, []
    for char in text:
        if char in "<([{":
            depth += 1
        elif char in ">)]}":
            depth -= 1
        if char == separator and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(char)
    if "".join(current).strip():
        parts.append("".join(current))
    return [part.strip() for part in parts if part.strip()]


def parse_api() -> dict[str, Function]:
    text = API.read_text(encoding="utf-8")
    text = re.sub(r"//[^\n]*", "", text)
    functions = {}
    for match in re.finditer(r"\bpub fn (\w+)\s*\(([^)]*)\)\s*(?:->\s*([^{]+))?\{", text):
        name, params, returns = match.group(1), match.group(2), (match.group(3) or "()").strip()
        parsed = []
        for param in split_top_level(params):
            param_name, param_type = param.split(":", 1)
            parsed.append((param_name.strip(), " ".join(param_type.split())))
        functions[name] = Function(name, parsed, " ".join(returns.split()))
    return functions


def camel(snake: str) -> str:
    head, *rest = snake.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def parse_dispatch() -> dict[str, tuple[list[tuple[str, str]], str]]:
    """Each read method's (argument name, decoder expression) list and result encoder."""
    text = DISPATCH.read_text(encoding="utf-8")
    body = text[text.index("pub fn dispatch_read") :]
    markers = list(re.finditer(r'\n        "(\w+)" =>', body))
    arms = {}
    for index, marker in enumerate(markers):
        method = marker.group(1)
        chunk_end = markers[index + 1].start() if index + 1 < len(markers) else len(body)
        arm = body[marker.end() : chunk_end]
        call = re.search(r"let result =\s*[\w:]+\((.*?)\);\n", arm, re.DOTALL)
        if call is None:
            raise GenerationError(f"dispatcher arm {method} has no call")
        arguments = []
        for argument in split_top_level(call.group(1)):
            field = re.search(r'args\.field\("(\w+)"\)', argument)
            if field is None:
                raise GenerationError(f"{method}: argument without a field: {argument}")
            arguments.append((field.group(1), argument.rstrip("?").strip()))
        rest = arm[call.end() :]
        result = re.search(r"Ok\((.*)\)\s*\n\s*\}\)\(\)", rest, re.DOTALL)
        if result is None:
            raise GenerationError(f"dispatcher arm {method} has no result encoder")
        arms[method] = (arguments, " ".join(result.group(1).split()))
    return arms


def mirror(decoder: str, value: str) -> str:
    """The encoder expression for `value` that `decoder` reads back."""
    decoder = decoder.strip()
    opt = re.fullmatch(r"w::opt_d\(args\.field\(\"\w+\"\), \|v\| (.*)\)", decoder, re.DOTALL) or re.fullmatch(
        r"w::opt_d\(v, \|v\| (.*)\)", decoder, re.DOTALL
    )
    if opt:
        return f"w::opt_e(&{value}, |v| {mirror_inner(opt.group(1))})"
    listed = re.fullmatch(r"w::list_d\(args\.field\(\"\w+\"\), \|v\| (.*)\)", decoder, re.DOTALL)
    if listed:
        return f"w::list_e(&{value}, |v| {mirror_inner(listed.group(1))})"
    simple = re.fullmatch(r"(w::\w+_d|dec_\w+)\(args\.field\(\"\w+\"\)\)", decoder)
    if simple:
        return encoder_for(simple.group(1), f"&{value}")
    raise GenerationError(f"cannot mirror decoder {decoder}")


def mirror_inner(decoder: str) -> str:
    decoder = decoder.strip()
    opt = re.fullmatch(r"w::opt_d\(v, \|v\| (.*)\)", decoder, re.DOTALL)
    if opt:
        return f"w::opt_e(v, |v| {mirror_inner(opt.group(1))})"
    listed = re.fullmatch(r"w::list_d\(v, \|v\| (.*)\)", decoder, re.DOTALL)
    if listed:
        return f"w::list_e(v, |v| {mirror_inner(listed.group(1))})"
    simple = re.fullmatch(r"(w::\w+_d|dec_\w+)\(v\)", decoder)
    if simple:
        return encoder_for(simple.group(1), "v")
    raise GenerationError(f"cannot mirror inner decoder {decoder}")


def encoder_for(decoder: str, value: str) -> str:
    if decoder.startswith("dec_"):
        return f"g::enc_{decoder[4:]}({value})"
    name = decoder.removeprefix("w::").removesuffix("_d")
    return f"w::{name}_e({value})"


def invert(encoder: str, value: str) -> str:
    """The decoder expression reading `value` that `encoder` (over `&result` or `v`) wrote."""
    encoder = encoder.strip()
    opt = re.fullmatch(r"w::opt_e\((?:&result|v), \|v\| (.*)\)", encoder, re.DOTALL)
    if opt:
        return f"w::opt_d({value}, |v| {invert(opt.group(1), 'v')})"
    listed = re.fullmatch(r"w::list_e\((?:&result|v), \|v\| (.*)\)", encoder, re.DOTALL)
    if listed:
        return f"w::list_d({value}, |v| {invert(listed.group(1), 'v')})"
    simple = re.fullmatch(r"(w::\w+_e|enc_\w+)\((?:&result|v)\)", encoder)
    if simple:
        name = simple.group(1)
        if name.startswith("enc_"):
            return f"g::dec_{name[4:]}({value})"
        return f"w::{name.removeprefix('w::').removesuffix('_e')}_d({value})"
    raise GenerationError(f"cannot invert result encoder {encoder}")


def owned(param_type: str) -> str:
    return param_type


def emit(functions: dict[str, Function], calls: list[str], surface: dict, arms: dict) -> str:
    read = set(surface["read"])
    custom = set(surface["custom"])
    for name in calls:
        if name not in functions:
            raise GenerationError(f"session call {name} is not an api function")
    missing = (read | custom) - set(calls)
    if missing:
        raise GenerationError(f"surface methods missing from the session calls: {sorted(missing)}")
    out = [
        HEADER,
        "//! The repository session call seam: every backend serves these calls; see",
        "//! `tooling/remote_wire/generate_calls.py`.",
        "#![allow(clippy::too_many_arguments, clippy::too_many_lines, unused_imports)]",
        "#![allow(clippy::needless_pass_by_value, clippy::redundant_closure, unused_variables)]",
        "",
        "use super::{CallError, CallResult, WireTransport};",
        "use crate::rt;",
        "use futures::future::{FutureExt, LocalBoxFuture};",
        "use gitlama_application::wire::generated as g;",
        "use gitlama_application::wire::runtime as w;",
        "use gitlama_core::api::*;",
        "use std::rc::Rc;",
        "",
        "/// The calls a repository session backend serves.",
        "pub trait SessionCalls {",
    ]
    for name in calls:
        function = functions[name]
        params = "".join(f", {n}: {owned(t)}" for n, t in function.params)
        out.append(
            f"    fn {name}(&self{params}) -> LocalBoxFuture<'static, CallResult<{function.returns}>>;"
        )
    out += ["}", "", "/// The in-process backend: each call runs on the blocking pool.", "pub struct LocalCalls;", ""]
    out.append("impl SessionCalls for LocalCalls {")
    for name in calls:
        function = functions[name]
        params = "".join(f", {n}: {owned(t)}" for n, t in function.params)
        args = ", ".join(n for n, _ in function.params)
        out.append(
            f"    fn {name}(&self{params}) -> LocalBoxFuture<'static, CallResult<{function.returns}>> {{"
        )
        out.append(f"        async move {{ Ok(rt::blocking(move || {name}({args})).await) }}.boxed_local()")
        out.append("    }")
    out += ["}", "", "/// One client function per read method the remote helper executes.", "pub mod wire_reads {"]
    out += ["    use super::*;", ""]
    for name in calls:
        if name not in read:
            continue
        function = functions[name]
        method = camel(name)
        if method not in arms:
            raise GenerationError(f"the helper dispatches no read method {method}")
        arguments, encoder = arms[method]
        if [camel(n) for n, _ in function.params] != [n for n, _ in arguments]:
            raise GenerationError(f"{method}: api parameters differ from the dispatcher's")
        params = "".join(f", {n}: {t}" for n, t in function.params)
        out.append(
            f"    pub async fn {name}(transport: Rc<dyn WireTransport>{params}) -> CallResult<{function.returns}> {{"
        )
        out.append("        let mut args = w::Map::new();")
        for (param, _), (field, decoder) in zip(function.params, arguments):
            if field == "sessionId":
                value = f"w::big_e(&transport.helper_session({param})?)"
            else:
                value = mirror(decoder, param)
            out.append(f'        args.insert("{field}".to_owned(), {value});')
        out.append(f'        let result = transport.invoke_read("{method}", w::Value::Object(args)).await?;')
        out.append(f"        {invert(encoder, '&result')}.map_err(CallError::Wire)")
        out.append("    }")
        out.append("")
    out += ["}", ""]
    out.append("/// The remote backend's routing over its transport and custom methods.")
    out.append("pub struct RemoteCalls<C: RemoteCustom> {")
    out.append("    pub custom: Rc<C>,")
    out.append("}")
    out.append("")
    out.append("impl<C: RemoteCustom + 'static> SessionCalls for RemoteCalls<C> {")
    for name in calls:
        function = functions[name]
        params = "".join(f", {n}: {t}" for n, t in function.params)
        args = "".join(f", {n}" for n, _ in function.params)
        out.append(
            f"    fn {name}(&self{params}) -> LocalBoxFuture<'static, CallResult<{function.returns}>> {{"
        )
        if name in read:
            out.append("        let custom = Rc::clone(&self.custom);")
            out.append(
                f"        wire_reads::{name}(self.custom.transport(){args})"
                ".map(move |result| result.map(|value| custom.adapt(value))).boxed_local()"
            )
        elif name in custom:
            out.append(f"        self.custom.{name}({', '.join(n for n, _ in function.params)})")
        else:
            out.append(f'        async {{ Err(CallError::Unsupported("{name}")) }}.boxed_local()')
        out.append("    }")
    out += ["}", ""]
    out.append("/// The custom methods a remote backend implements by hand.")
    out.append("pub trait RemoteCustom {")
    out.append("    fn transport(&self) -> Rc<dyn WireTransport>;")
    out.append("    /// Adjusts a read result: a connection marks host paths with its authority.")
    out.append("    fn adapt<T: 'static>(&self, value: T) -> T {")
    out.append("        value")
    out.append("    }")
    for name in calls:
        if name not in custom:
            continue
        function = functions[name]
        params = "".join(f", {n}: {t}" for n, t in function.params)
        out.append(
            f"    fn {name}(&self{params}) -> LocalBoxFuture<'static, CallResult<{function.returns}>>;"
        )
    out.append("}")
    out.append("")
    out.append("/// Where a call runs: the backend of a session or of a path's authority.")
    out.append("pub trait CallRouter {")
    out.append("    /// The in-process backend.")
    out.append("    fn local(&self) -> Rc<dyn SessionCalls>;")
    out.append("    /// The backend of `session_id`; `None` when its connection is gone.")
    out.append("    fn for_session(&self, session_id: u64) -> Option<Rc<dyn SessionCalls>>;")
    out.append("    /// The backend of `identity`'s location; `None` when its host is not connected.")
    out.append("    fn for_identity(&self, identity: &NativePathIdentity) -> Option<Rc<dyn SessionCalls>>;")
    out.append("}")
    out.append("")
    out.append("/// Hands every call to the backend its session or path belongs to.")
    out.append("pub struct RoutedCalls<R: CallRouter> {")
    out.append("    pub router: Rc<R>,")
    out.append("}")
    out.append("")
    out.append("impl<R: CallRouter + 'static> SessionCalls for RoutedCalls<R> {")
    for name in calls:
        function = functions[name]
        params = "".join(f", {n}: {owned(t)}" for n, t in function.params)
        args = ", ".join(n for n, _ in function.params)
        out.append(
            f"    fn {name}(&self{params}) -> LocalBoxFuture<'static, CallResult<{function.returns}>> {{"
        )
        first = function.params[0] if function.params else None
        if first and first[0] == "session_id":
            backend = "self.router.for_session(session_id)"
        elif first and first[1] == "NativePathIdentity":
            backend = f"self.router.for_identity(&{first[0]})"
        else:
            backend = None
        if backend is None:
            out.append(f"        self.router.local().{name}({args})")
        else:
            out.append(f"        match {backend} {{")
            out.append(f"            Some(backend) => backend.{name}({args}),")
            out.append('            None => async { Err(CallError::Transport("disconnected".to_owned())) }.boxed_local(),')
            out.append("        }")
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def rustfmt(source: str) -> str:
    rustfmt_path = shutil.which("rustfmt")
    if rustfmt_path is None:
        return source
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "calls.rs"
        path.write_text(source, encoding="utf-8")
        subprocess.run(
            [rustfmt_path, "--edition", "2024", str(path)], check=True, capture_output=True
        )
        return path.read_text(encoding="utf-8")


def main() -> int:
    functions = parse_api()
    calls = json.loads(CALLS.read_text(encoding="utf-8"))["calls"]
    surface = json.loads(SURFACE.read_text(encoding="utf-8"))
    arms = parse_dispatch()
    text = rustfmt(emit(functions, calls, surface, arms))
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except GenerationError as error:
        print(f"generation failed: {error}", file=sys.stderr)
        sys.exit(1)
