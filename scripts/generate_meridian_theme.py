#!/usr/bin/env python3
"""Generate qml/GitLama/GitColors.qml from docs/design-system/tokens/gitlama-tokens.json.

Meridian owns the shared tokens (surfaces, ink, status, series, spacing,
radius, type). GitLama generates only its git colours, the tokens no other
Meridian app needs, and checks that the shared values in its design reference
still equal the vendored Meridian QML module's GitLama palette.

Usage:
  python3 scripts/generate_meridian_theme.py          # write the QML singleton
  python3 scripts/generate_meridian_theme.py --check  # exit 1 if stale or drifted
Never edit the generated file by hand.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/design-system/tokens/gitlama-tokens.json"
TARGET = ROOT / "qml/GitLama/GitColors.qml"

# Tokens only a Git client needs. Everything else comes from meridian_ui.
GIT_TOKENS = (
    "added-strong",
    "deleted",
    "deleted-bg",
    "deleted-strong",
    "renamed",
    "side-ours",
    "side-theirs",
    "tag-ink",
    "tag-bg",
    "lama-shades",
)

# GitLama's reference names for Meridian's shared tokens.
SHARED_NAMES = {
    "polar": "accent",
    "on-polar": "ink-on-accent",
    "on-polar-muted": "ink-on-accent-muted",
    "on-danger": "ink-on-danger",
    "polar-soft": "accent-soft",
    "polar-ink": "accent-ink",
    "fjord": "brand",
    "added": "success",
    "added-bg": "success-bg",
    "modified": "warning",
    "modified-bg": "warning-bg",
    "conflict": "attention",
    "conflict-bg": "attention-bg",
    **{f"lane-{n}": f"series-{n}" for n in range(1, 9)},
}


def camel(name: str) -> str:
    parts = re.split(r"[-.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def color_literal(value: str) -> str:
    hex_value = value.strip().lstrip("#")
    if len(hex_value) == 6:
        return f'"#{hex_value.lower()}"'
    raise SystemExit(f"unsupported colour value: {value}")


def generate(tokens: dict) -> str:
    colors = {t["name"]: t for t in tokens["color"]["tokens"]}
    git = [colors[name] for name in GIT_TOKENS]
    lines = [
        "// GENERATED by scripts/generate_meridian_theme.py from",
        "// docs/design-system/tokens/gitlama-tokens.json. Do not edit by hand.",
        "pragma Singleton",
        "import QtQuick",
        "import Meridian",
        "",
        "// GitLama's own colours: the diff, rename, conflict-side and tag tokens",
        "// that only a Git client needs, and the brand lama's. They follow",
        "// Meridian's light or dark theme.",
        "QtObject {",
    ]
    for token in git:
        name = camel(token["name"])
        lines.append(f"    /// {token['usage']}")
        lines.append(
            f"    readonly property color {name}: Theme.dark ? {color_literal(token['value']['dark'])}"
            f" : {color_literal(token['value']['light'])}"
        )
    lines.append("}")
    return "\n".join(lines) + "\n"


def meridian_palette() -> dict:
    """The vendored Meridian QML module's GitLama palette."""
    text = (ROOT / "qml/Meridian/Tokens.qml").read_text(encoding="utf-8")
    match = re.search(r"readonly property var palettes: \((\{.*\})\)\s*$", text, re.MULTILINE)
    if not match:
        raise SystemExit("qml/Meridian/Tokens.qml has no palettes")
    return json.loads(match.group(1))["gitlama"]


def kebab_to_camel(name: str) -> str:
    return camel(name)


def normalized(value: str) -> str:
    """A colour as #AARRGGBB, from #RRGGBB, #AARRGGBB or RGBA(r,g,b,a)."""
    value = value.strip().upper()
    match = re.fullmatch(r"RGBA\((\d+),(\d+),(\d+),([0-9.]+)\)", value.replace(" ", ""))
    if match:
        r, g, b = (int(match.group(i)) for i in (1, 2, 3))
        alpha = round(float(match.group(4)) * 255)
        return f"#{alpha:02X}{r:02X}{g:02X}{b:02X}"
    if len(value) == 7:
        return "#FF" + value[1:]
    return value


def drift(tokens: dict) -> list[str]:
    """Differences between the design reference and the vendored Meridian."""
    palette = meridian_palette()
    errors = []
    for token in tokens["color"]["tokens"]:
        name = token["name"]
        if name in GIT_TOKENS:
            continue
        target = camel(SHARED_NAMES.get(name, name))
        for theme in ("light", "dark"):
            if target not in palette[theme]:
                errors.append(f"{name} has no Meridian token {target}")
                break
            ours = normalized(token["value"][theme])
            theirs = normalized(str(palette[theme][target]))
            if ours != theirs:
                errors.append(f"{name} ({theme}) is {ours}, Meridian {target} is {theirs}")
    return errors


def main() -> None:
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    text = generate(tokens)
    if "--check" in sys.argv:
        problems = drift(tokens)
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            problems.append(f"{TARGET.relative_to(ROOT)} is stale: run scripts/generate_meridian_theme.py")
        if problems:
            raise SystemExit("\n".join(problems))
        print("GitLama git colours are current and the shared tokens match Meridian")
        return
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
