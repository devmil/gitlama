#!/usr/bin/env python3
"""Generate lib/app/gitlama_tokens.g.dart from docs/design-system/tokens/gitlama-tokens.json.

meridian_ui owns the shared Meridian tokens (surfaces, ink, status, series,
spacing, radius, type). GitLama generates only its git colours, the tokens
no other Meridian app needs, and checks that the shared values in its design
reference still equal the pinned meridian_ui core and GitLama brand.

Usage:
  python3 scripts/generate_meridian_theme.py          # write the Dart file
  python3 scripts/generate_meridian_theme.py --check  # exit 1 if stale or drifted
Never edit the generated file by hand.
"""
from pathlib import Path
import json
import re
import shutil
import subprocess
import sys
import tempfile
from urllib.parse import urlparse
from urllib.request import url2pathname

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/design-system/tokens/gitlama-tokens.json"
TARGET = ROOT / "lib/app/gitlama_tokens.g.dart"

# Tokens only a Git client needs. Everything else comes from meridian_ui.
GIT_TOKENS = (
    "added-strong",
    "deleted",
    "deleted-bg",
    "deleted-strong",
    "renamed",
    "side-ours",
    "side-theirs",
    "tag-ink",
    "tag-bg",
)

# GitLama's reference names for Meridian's shared tokens.
SHARED_NAMES = {
    "polar": "accent",
    "on-polar": "on-accent",
    "on-polar-muted": "on-accent-muted",
    "polar-soft": "accent-soft",
    "polar-ink": "accent-ink",
    "fjord": "brand",
    "added": "success",
    "added-bg": "success-bg",
    "modified": "warning",
    "modified-bg": "warning-bg",
    "conflict": "attention",
    "conflict-bg": "attention-bg",
    **{f"lane-{n}": f"series-{n}" for n in range(1, 9)},
}


def camel(name: str) -> str:
    parts = re.split(r"[-.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def color_literal(value: str) -> str:
    hex_value = value.strip().lstrip("#")
    if len(hex_value) == 6:
        return f"Color(0xFF{hex_value.upper()})"
    raise SystemExit(f"unsupported colour value: {value}")


def formatted(source: str) -> str:
    """Return the source exactly as `dart format` would write it."""
    dart = shutil.which("dart")
    if dart is None:
        raise SystemExit("dart is required (use the pinned Flutter SDK)")
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "gitlama_tokens.g.dart"
        path.write_text(source, encoding="utf-8")
        subprocess.run([dart, "format", str(path)], check=True, capture_output=True)
        return path.read_text(encoding="utf-8")


def generate(tokens: dict) -> str:
    colors = {t["name"]: t for t in tokens["color"]["tokens"]}
    git = [colors[name] for name in GIT_TOKENS]
    lines = [
        "// GENERATED by scripts/generate_meridian_theme.py from",
        "// docs/design-system/tokens/gitlama-tokens.json. Do not edit by hand.",
        "",
        "import 'package:flutter/material.dart';",
        "",
        "/// GitLama's git colours: the diff, rename, conflict-side and tag",
        "/// tokens that only a Git client needs. Read them with `context.git`.",
        "@immutable",
        "final class GitLamaGitColors extends ThemeExtension<GitLamaGitColors> {",
        "  const GitLamaGitColors({",
    ]
    lines += [f"    required this.{camel(t['name'])}," for t in git]
    lines += ["  });", ""]
    for token in git:
        lines.append(f"  /// {token['usage']}")
        lines.append(f"  final Color {camel(token['name'])};")
    for theme in ("light", "dark"):
        lines += ["", f"  static const {theme} = GitLamaGitColors("]
        lines += [f"    {camel(t['name'])}: {color_literal(t['value'][theme])}," for t in git]
        lines.append("  );")
    lines += ["", "  @override", "  GitLamaGitColors copyWith() => this;", ""]
    lines += [
        "  @override",
        "  GitLamaGitColors lerp(covariant GitLamaGitColors? other, double t) {",
        "    if (other == null) return this;",
        "    return GitLamaGitColors(",
    ]
    lines += [
        f"      {camel(t['name'])}: Color.lerp({camel(t['name'])}, other.{camel(t['name'])}, t)!,"
        for t in git
    ]
    lines += ["    );", "  }", "}"]
    return formatted("\n".join(lines) + "\n")


def meridian_root() -> Path:
    config = json.loads((ROOT / ".dart_tool/package_config.json").read_text(encoding="utf-8"))
    for package in config["packages"]:
        if package["name"] == "meridian_ui":
            uri = package["rootUri"]
            if uri.startswith("file:"):
                return Path(url2pathname(urlparse(uri).path))
            return (ROOT / ".dart_tool" / uri).resolve()
    raise SystemExit("meridian_ui is not resolved: run flutter pub get")


def drift(tokens: dict) -> list[str]:
    """Differences between the design reference and the pinned meridian_ui."""
    package = meridian_root()
    core = json.loads((package / "tokens/meridian.tokens.json").read_text(encoding="utf-8"))
    brand = json.loads((package / "tokens/brands/gitlama.json").read_text(encoding="utf-8"))
    shared = {t["name"]: t["value"] for t in core["color"]["tokens"]}
    for theme in ("light", "dark"):
        for name, value in brand["colors"][theme].items():
            shared.setdefault(name, {})[theme] = value
    errors = []
    for token in tokens["color"]["tokens"]:
        name = token["name"]
        if name in GIT_TOKENS:
            continue
        target = SHARED_NAMES.get(name, name)
        if target not in shared:
            errors.append(f"{name} has no meridian_ui token {target}")
            continue
        for theme in ("light", "dark"):
            ours = token["value"][theme].upper()
            theirs = str(shared[target][theme]).upper()
            if ours != theirs:
                errors.append(f"{name} ({theme}) is {ours}, meridian_ui {target} is {theirs}")
    return errors


def main() -> None:
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    text = generate(tokens)
    if "--check" in sys.argv:
        problems = drift(tokens)
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            problems.append(f"{TARGET.relative_to(ROOT)} is stale: run scripts/generate_meridian_theme.py")
        if problems:
            raise SystemExit("\n".join(problems))
        print("GitLama git colours are current and the shared tokens match meridian_ui")
        return
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
